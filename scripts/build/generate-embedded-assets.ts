#!/usr/bin/env bun
import fs from "fs";
import path from "path";
import {
    assertFrontendEntryAssets,
    getFrontendEntryAssets,
    type ViteManifest,
} from "@/server/frontend-entry-assets.js";

const projectRoot = path.resolve(import.meta.dirname, "../..");
const distDir = path.join(projectRoot, "dist");
const outputDir = path.join(projectRoot, "out");
const outputFile = path.join(outputDir, "embedded-assets-entry.ts");
const databaseTemplateFile = path.join(outputDir, "kuma.db");
const viteManifestFile = path.join(distDir, ".vite/manifest.json");

function walkFiles(dir: string, root = dir): string[] {
    const entries = fs.readdirSync(dir, { withFileTypes: true });
    const files: string[] = [];

    for (const entry of entries) {
        const fullPath = path.join(dir, entry.name);
        if (entry.isDirectory()) {
            files.push(...walkFiles(fullPath, root));
            continue;
        }

        files.push(path.relative(root, fullPath).split(path.sep).join("/"));
    }

    return files.sort();
}

function toImportId(index: number) {
    return `asset_${index}`;
}

function toImportPath(relativePath: string) {
    return `../dist/${relativePath.split("/").join("/")}`;
}

if (!fs.existsSync(distDir)) {
    console.error("dist/ not found. Run `bun run build:frontend` first.");
    process.exit(1);
}

const webAssets = walkFiles(distDir).filter((webPath) => !webPath.startsWith(".vite/"));
if (webAssets.length === 0) {
    console.error("dist/ is empty. Run `bun run build:frontend` first.");
    process.exit(1);
}

if (!fs.existsSync(viteManifestFile)) {
    console.error("Vite manifest not found. Run `bun run build:frontend` first.");
    process.exit(1);
}

if (!fs.existsSync(databaseTemplateFile)) {
    console.error("out/kuma.db not found. Run `bun run build:kuma-db` first.");
    process.exit(1);
}

const manifest = JSON.parse(fs.readFileSync(viteManifestFile, "utf8")) as ViteManifest;
const entryAssets = getFrontendEntryAssets(manifest);
assertFrontendEntryAssets(entryAssets, webAssets);

const importLines: string[] = [];
const mapEntries: string[] = [];

for (let i = 0; i < webAssets.length; i++) {
    const webPath = webAssets[i];
    const importId = toImportId(i);
    importLines.push(`import ${importId} from "${toImportPath(webPath)}" with { type: "file" };`);
    mapEntries.push(`    "${webPath}": ${importId},`);
}

fs.mkdirSync(outputDir, { recursive: true });

const source = `// @ts-nocheck
// AUTO-GENERATED by scripts/build/generate-embedded-assets.ts — do not edit.

import dbTemplate from "./kuma.db" with { type: "file" };
import { registerDatabaseTemplate } from "../src/server/database-template";
import { registerEmbeddedAssets } from "../src/server/embedded-assets";
import { registerFrontendEntryAssets } from "../src/server/frontend-entry-assets";
${importLines.join("\n")}

const embeddedWebAssets = {
${mapEntries.join("\n")}
};

registerDatabaseTemplate(dbTemplate);
registerEmbeddedAssets(embeddedWebAssets);
registerFrontendEntryAssets(${JSON.stringify(entryAssets, null, 4)});

await import("../src/server/server.ts");
`;

fs.writeFileSync(outputFile, source);
console.log(`Generated ${outputFile} with ${webAssets.length} embedded web assets.`);
